// Regenerates mawaqit-times.js from the mosque's public Mawaqit page.
// Usage: node tools/update-mawaqit-times.mjs [saved-page.html]
// With no argument the page is downloaded. Fails (exit 1, file untouched) if the data looks wrong.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parseMawaqitPage, MOSQUE_URL } from "../mawaqit-worker/src/parse.js";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "mawaqit-times.js");
const file = process.argv[2];
const html = file ? readFileSync(file, "utf8") : await (await fetch(MOSQUE_URL)).text();
const out = parseMawaqitPage(html);
writeFileSync(OUT, `// Generated by tools/update-mawaqit-times.mjs from the mosque's public Mawaqit page. Do not edit by hand.\n// adhan rows: fajr shuruq dhuhr asr maghrib isha. iqama rows (jamaat): fajr dhuhr asr maghrib isha.\nwindow.MAWAQIT_TIMES=${JSON.stringify(out)};\n`);
console.log(`Wrote mawaqit-times.js (${out.mosque}, fetched ${out.fetched}).`);
